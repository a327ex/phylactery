"""port_programs.py <program_map.json> <out dir> -- the port to Anchor: three.js's compiled programs
(GAME.program_map_write in the web build) as the Anchor build's program library:
  <out>/NN.vs.glsl, NN.fs.glsl   one pair per distinct program
  <out>/programs.lua             return { [key] = NN, ... }  (key: material.name|scene|side|instanced)
Shadow depth programs collapse to depth|- and depth|i: three.js reuses the shared depth material's
program whatever side it is set to (the side is changed without a version bump), and the variants
differ only in defines that do not touch the packed depth (sidedness, a map with alphaTest 0)."""
import json, sys, os
m = json.load(open(sys.argv[1]))
out = sys.argv[2]
os.makedirs(out, exist_ok=True)
ck_index, keys = {}, {}
def index_of(ck):
    if ck not in ck_index:
        n = len(ck_index) + 1
        ck_index[ck] = n
        p = m['programs'][ck]
        open(os.path.join(out, f'{n:02d}.vs.glsl'), 'w', encoding='utf-8', newline='\n').write(p['vs'])
        open(os.path.join(out, f'{n:02d}.fs.glsl'), 'w', encoding='utf-8', newline='\n').write(p['fs'])
    return ck_index[ck]
depth = {}
for key, ck in sorted(m['keys'].items()):
    if key.startswith('depth|'):
        inst = key.split('|')[2]
        cands = [ck] + m['conflicts'].get(key, [])
        # prefer a variant without a map (fewer bindings); all draw the same depth
        best = sorted(cands, key=lambda c: (',uv,' in c, c))[0]
        depth.setdefault(inst, best)
        continue
    keys[key] = index_of(ck)
for inst, ck in depth.items(): keys[f'depth|{inst}'] = index_of(ck)
with open(os.path.join(out, 'programs.lua'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('-- generated by tools/port_programs.py from the three.js build: key -> program file number\nreturn {\n')
    for k in sorted(keys): f.write(f'  [{json.dumps(k)}] = {keys[k]},\n')
    f.write('}\n')
print(len(keys), 'keys,', len(ck_index), 'programs ->', out)
