"""port_assets.py <export dir> <group> -- the port to Anchor: an export from the three.js build
(GAME.port_export, web/src/port_export.js) filed under assets/port/<group>/ (the binary files) with
assets/port/<group>.lua, the manifest as a Lua table the Anchor build loads."""
import json, os, shutil, sys
sys.path.insert(0, os.path.dirname(__file__))
from glcap_to_lua import lua   # the JSON -> Lua literal writer

src, group = sys.argv[1], sys.argv[2]
root = os.path.join(os.path.dirname(__file__), '..', 'assets', 'port')
dst = os.path.join(root, group)
if os.path.isdir(dst): shutil.rmtree(dst)
for sub in ('geo', 'tex'):
    if os.path.isdir(os.path.join(src, sub)): shutil.copytree(os.path.join(src, sub), os.path.join(dst, sub))
m = json.load(open(os.path.join(src, 'manifest.json')))
m['dir'] = f'assets/port/{group}'
open(os.path.join(root, group + '.lua'), 'w', encoding='utf-8', newline='\n').write(
    '-- generated by tools/port_assets.py from the three.js build (web/src/port_export.js)\nreturn ' + lua(m) + '\n')
n = sum(len(fs) for _, _, fs in os.walk(dst))
print(f'{group}: {n} files, manifest assets/port/{group}.lua')
