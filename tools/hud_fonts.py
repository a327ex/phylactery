"""hud_fonts.py -- round 42: pixel fonts for the HUD, as glyph tables (port/hud_fonts.lua).

hud.lua draws its own bitmap font (each text rasterized once, with its outline and drop); this
turns TrueType pixel fonts into the same kind of table: each glyph's pixels, rendered without
anti-aliasing at the size where the font sits on whole pixels, relative to the top of its capitals,
and its advance. Fonts (OFL, assets/fonts/, from github.com/google/fonts):
  silk      Silkscreen 8          small capitals, wide
  tiny      Tiny5 8               small, mixed case
  pixelify  Pixelify Sans 11      rounded, mixed case
  bastarda  Jacquarda Bastarda 9  calligraphic (13 px), mixed case
  jacquard  Jacquard 12           blackletter (21 px), titles
Usage: python tools/hud_fonts.py
"""
import os
import numpy as np
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
FONTS = [
    ('silk', 'Silkscreen-Regular.ttf', 8, True),
    ('tiny', 'Tiny5-Regular.ttf', 8, False),
    ('pixelify', 'PixelifySans[wght].ttf', 11, False),
    ('bastarda', 'JacquardaBastarda9-Regular.ttf', 13, False),
    ('jacquard', 'Jacquard12-Regular.ttf', 21, False),
]
CHARS = [chr(c) for c in range(33, 127)]

def glyph_pixels(font, ch, size):
    W = size * 4
    im = Image.new('1', (W, W), 0); d = ImageDraw.Draw(im); d.fontmode = '1'
    d.text((size, size), ch, font=font, fill=1, anchor='ls')     # origin on the baseline
    a = np.asarray(im)
    ys, xs = np.nonzero(a)
    return [(int(x) - size, int(y) - size) for x, y in zip(xs, ys)]   # x from the pen, y from the baseline (negative up)

def main():
    out = ['-- generated by tools/hud_fonts.py (round 42): pixel fonts as glyph tables for hud.lua', 'return {']
    for name, file, size, upper in FONTS:
        font = ImageFont.truetype(os.path.join(ROOT, 'assets', 'fonts', file), size)
        g = {ch: glyph_pixels(font, ch, size) for ch in CHARS}
        cap_top = min(y for ch in 'ABCDEFGHIKLMNOPRSTUVWXYZ' for _, y in g[ch]) if g['A'] else -size
        bottom = max((y for ch in CHARS for _, y in g[ch]), default=0)
        h = bottom - cap_top + 1
        space = round(font.getlength(' '))
        out.append('  %s = { h = %d, cap = %d, upper = %s, space = %d, glyphs = {' % (name, h, -cap_top, 'true' if upper else 'false', space))
        for ch in CHARS:
            px = g[ch]
            adv = round(font.getlength(ch))
            flat = ','.join('%d,%d' % (x, y - cap_top) for x, y in px)
            key = repr(ch) if ch not in ("'", '\\') else ('"\'"' if ch == "'" else "'\\\\'")
            out.append('    [%s] = { w = %d, px = { %s } },' % (key, adv, flat))
        out.append('  } },')
        print('%-9s size %2d: height %d (capitals %d), space %d' % (name, size, h, -cap_top, space))
    out.append('}')
    open(os.path.join(ROOT, 'port', 'hud_fonts.lua'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')

if __name__ == '__main__':
    main()
