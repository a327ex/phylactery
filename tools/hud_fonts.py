"""hud_fonts.py -- the HUD's font as a glyph table (port/hud_fonts.lua), from tools/bitmap_fonts.py.

FACET (owner, 2026-10-03, round 43: "Let's go with faceted"): capitals whose rounds are cut into planes,
like the cave's broken rock; 7 rows; each advance is the letter's width and the 1 px after it.
Usage: python tools/hud_fonts.py
"""
import os, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bitmap_fonts as BF

def lua_key(ch):
    if ch == "'": return '"\'"'
    if ch == '\\': return "'\\\\'"
    return repr(ch)

def main():
    rows = 7
    glyphs = dict(BF.PUNCT); glyphs.update(BF.FACET)
    out = ['-- generated by tools/hud_fonts.py: the HUD\'s font as a glyph table (pixels from the top of the capitals)',
           'return {', '  facet = { h = %d, cap = %d, upper = true, space = 3, glyphs = {' % (rows, rows)]
    for ch, rr in sorted(glyphs.items()):
        off = rows - len(rr)                                      # (shorter glyphs sit on the baseline)
        px = [(x, y + off) for y, row in enumerate(rr) for x, c in enumerate(row) if c == '#']
        out.append('    [%s] = { w = %d, px = { %s } },' % (lua_key(ch), len(rr[0]) + 1, ','.join('%d,%d' % q for q in px)))
    out += ['  } },', '}']
    open(os.path.join(ROOT, 'port', 'hud_fonts.lua'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    print('facet: %d glyphs' % len(glyphs))

if __name__ == '__main__':
    main()
